// Lucide icons (https://lucide.dev), embedded as SVG source and rendered through NSImage as
// tintable template images. This keeps the icons crisp at any size and lets them follow the
// surrounding foregroundStyle, just like SF Symbols did.
@MainActor
enum LucideIconStore {
    private static var cache: [String: NSImage] = [:]

    /// A shared template image for the named icon, optionally with a custom stroke width.
    static func image(_ name: String, lineWidth: CGFloat = 2) -> NSImage {
        let key = "\(name)#\(lineWidth)"
        if let cached = cache[key] { return cached }

        var svg = svgSources[name] ?? svgSources["download"] ?? ""
        if lineWidth != 2 {
            svg = svg.replacingOccurrences(of: "stroke-width=\"2\"", with: "stroke-width=\"\(lineWidth)\"")
        }

        let image = NSImage(data: Data(svg.utf8)) ?? NSImage(size: NSSize(width: 24, height: 24))
        image.isTemplate = true
        cache[key] = image
        return image
    }

    /// A sized copy suitable for NSMenuItem.image (menus can't take SwiftUI views).
    static func menuImage(_ name: String, pointSize: CGFloat = 14) -> NSImage {
        let copy = (image(name).copy() as? NSImage) ?? image(name)
        copy.size = NSSize(width: pointSize, height: pointSize)
        copy.isTemplate = true
        return copy
    }

