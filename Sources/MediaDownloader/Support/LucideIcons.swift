/// A Lucide icon that behaves like an SF Symbol: sized via `size`, colored via `foregroundStyle`.
struct LucideIcon: View {
    let name: String
    var size: CGFloat = 16
    var lineWidth: CGFloat = 2

    var body: some View {
        Image(nsImage: LucideIconStore.image(name, lineWidth: lineWidth))
            .resizable()
            .renderingMode(.template)
            .interpolation(.high)
            .frame(width: size, height: size)
    }
}
